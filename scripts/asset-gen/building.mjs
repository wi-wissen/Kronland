// Create buildings from the icon atlas: icon (128 px) → concept image (image model) → Meshy 7.1 (one image) →
// one GLB with levels of detail per player colour.
//
//   node scripts/asset-gen/building.mjs concept <id>   # concept from the icon (assets-src/buildings/<id>/concept.png)
//     [--model openai/gpt-5.4-image-2] [--out a]       # variant concept-a.png; pick <id> a adopts it
//   node scripts/asset-gen/building.mjs set castle,castle2,castle3 | cut castle,castle2,castle3 set-v2.png   # all levels in one image, cut out
//   node scripts/asset-gen/building.mjs winter <id>    # winter version of a tree/bush → <id>_winter/concept.png
//   node scripts/asset-gen/building.mjs model <id>     # Meshy: image → 3D (raw.glb)
//   node scripts/asset-gen/building.mjs build <id>     # → public/models/buildings/<file>_<colour>.glb (+ .lod1/.lod2)
//   node scripts/asset-gen/building.mjs all <id>
