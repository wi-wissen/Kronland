/** Split an image into n content columns (background from the corners), each column square with margin. */
async function splitColumns(file, n) {
  const { data, info } = await sharp(file).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const W = info.width, H = info.height, px = (x, y) => (y * W + x) * 3;
  const corners = [[2, 2], [W - 3, 2], [2, H - 3], [W - 3, H - 3]];
  const bg = [0, 1, 2].map((c) => corners.reduce((a, [x, y]) => a + data[px(x, y) + c], 0) / 4);
  const fg = (x, y) => Math.abs(data[px(x, y)] - bg[0]) + Math.abs(data[px(x, y) + 1] - bg[1]) + Math.abs(data[px(x, y) + 2] - bg[2]) > 45;
  const col = Array.from({ length: W }, (_, x) => { let c = 0; for (let y = 0; y < H; y += 2) if (fg(x, y)) c++; return c; });
  let runs = [], s = -1;
  for (let x = 0; x <= W; x++) { const on = x < W && col[x] > 2; if (on && s < 0) s = x; if (!on && s >= 0) { runs.push([s, x]); s = -1; } }
  // close small gaps within a building until n parts remain
  while (runs.length > n) {
    let best = 1; for (let i = 1; i < runs.length; i++) if (runs[i][0] - runs[i - 1][1] < runs[best][0] - runs[best - 1][1]) best = i;
    runs.splice(best - 1, 2, [runs[best - 1][0], runs[best][1]]);
  }
  if (runs.length < n) throw new Error(`Found only ${runs.length} of ${n} buildings in the image`);
  const out = [];
  for (const [x0, x1] of runs) {
    // take the tallest contiguous block (labels below the building drop out)
    const rowOn = (y) => { for (let x = x0; x < x1; x += 2) if (fg(x, y)) return true; return false; };
    let y0 = 0, y1 = -1, ys = -1, gap = 0;
    for (let y = 0; y <= H; y++) {
      const on = y < H && rowOn(y);
      if (on) { if (ys < 0) ys = y; gap = 0; continue; }
      if (ys >= 0 && (++gap > 12 || y === H)) { const e = y - gap; if (e - ys > y1 - y0) { y0 = ys; y1 = e; } ys = -1; }
    }
    const w = x1 - x0, h = y1 - y0 + 1, side = Math.round(Math.max(w, h) * 1.12);
    const crop = await sharp(file).extract({ left: x0, top: y0, width: w, height: h }).toBuffer();
    const sq = await sharp({ create: { width: side, height: side, channels: 3, background: { r: bg[0], g: bg[1], b: bg[2] } } })
      .composite([{ input: crop, left: Math.round((side - w) / 2), top: Math.round((side - h) / 2) }]).png().toBuffer();
    out.push(await sharp(sq).resize(1024, 1024).png().toBuffer());
  }
  return out;
}

