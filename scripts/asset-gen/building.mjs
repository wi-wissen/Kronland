/** Icon from the atlas, enlarged (reference for the image model). */
async function iconImage(name, size = 512) {
  const layout = JSON.parse(fs.readFileSync(path.join(ROOT, 'assets-src/icons/layout.json'), 'utf8'));
  const i = layout.names.indexOf(name);
  if (i < 0) throw new Error(`Icon ${name} missing in the atlas`);
  const atlas = path.join(ROOT, 'public/icons/symbols.webp');
  const cs = (await sharp(atlas).metadata()).width / layout.cols;
  return sharp(atlas).extract({ left: (i % layout.cols) * cs, top: Math.floor(i / layout.cols) * cs, width: cs, height: cs })
    .resize(size, size, { kernel: 'lanczos3' }).flatten({ background: '#ffffff' }).png().toBuffer();
}

