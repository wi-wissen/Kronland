async function concept(id, opts = {}) {
  const spec = readSpec(id), dir = dirOf(id);
  // Image 1: approved previous stage (spec.from) or the icon from the atlas; image 2: style template
  let first;
  if (spec.from) first = fs.readFileSync(path.join(dirOf(spec.from), 'concept.png'));
  else { first = await iconImage(spec.icon); fs.writeFileSync(path.join(dir, 'icon.png'), first); }
  // keep references small (input image tokens cost too): the model recognises style and shape even at 512 px
  const refs = [await sharp(first).resize(512, 512, { fit: 'inside' }).png().toBuffer(), await sharp(STYLE_HOUSE).resize(768).png().toBuffer()];
  const prompt = CONCEPT_PROMPT(spec.describe, !!spec.from, spec.level);
  const imageModel = opts.model ?? spec.imageModel ?? IMAGE_MODEL;
  const { buf, cost } = await generateImage(imageModel, prompt, refs);
  const res = { usage: { cost } };
  // --out <name>: variant for comparison (concept-<name>.png), concept.png stays
  const out = path.join(dir, opts.out ? `concept-${opts.out}.png` : 'concept.png');
  if (!opts.out && fs.existsSync(out)) { let n = 1; while (fs.existsSync(path.join(dir, `concept-v${n}.png`))) n++; fs.renameSync(out, path.join(dir, `concept-v${n}.png`)); }
  fs.writeFileSync(out, buf);
  const job = loadJob(id);
  (job.concepts ??= []).push({ model: imageModel, prompt, from: spec.from ?? spec.icon, file: path.basename(out), cost: res.usage?.cost });
  if (!opts.out && job.model) { (job.oldModels ??= []).push(job.model); delete job.model; } // new concept → the old model no longer applies
  saveJob(id, job);
  console.log(out, res.usage?.cost ? `(${res.usage.cost.toFixed(3)} $, ${JSON.stringify(res.usage.completion_tokens_details ?? {})} ${res.usage.prompt_tokens}/${res.usage.completion_tokens} tokens)` : '');
}

