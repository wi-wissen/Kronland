/** concept.png = chosen variant (concept-<name>.png). */
function pick(id, name) {
  const dir = dirOf(id), out = path.join(dir, 'concept.png');
  if (fs.existsSync(out)) { let n = 1; while (fs.existsSync(path.join(dir, `concept-v${n}.png`))) n++; fs.renameSync(out, path.join(dir, `concept-v${n}.png`)); }
  fs.copyFileSync(path.join(dir, `concept-${name}.png`), out);
  const job = loadJob(id);
  if (job.model) { (job.oldModels ??= []).push(job.model); delete job.model; }
  job.picked = name;
  saveJob(id, job);
}

async function model(id) {
  const spec = readSpec(id), dir = dirOf(id), job = loadJob(id);
  if (!job.model?.task) {
    spend(30, `${id}: building model`);
    // With back view (concept-back.png, see `back`): Meshy gets both sides (same price)
    const back = path.join(dir, 'concept-back.png');
    const multi = fs.existsSync(back);
    const base = {
      ai_model: 'meshy-7.1', should_texture: true, enable_pbr: true,
      should_remesh: true, topology: 'triangle', target_polycount: spec.polycount ?? 8000, remove_lighting: true,
      target_formats: ['glb'], origin_at: 'bottom',
    };
    const params = multi
      ? { ...base, image_urls: [dataUri(path.join(dir, 'concept.png')), dataUri(back)] }
      : { ...base, image_url: dataUri(path.join(dir, 'concept.png')) };
    const { result } = await meshy(multi ? 'v1/multi-image-to-3d' : 'v1/image-to-3d', params);
    job.model = { task: result, endpoint: multi ? 'v1/multi-image-to-3d' : 'v1/image-to-3d', params: { ...base, images: multi ? ['concept.png', 'concept-back.png'] : ['concept.png'] } };
    saveJob(id, job);
  }
  const t = await meshyWait(job.model.endpoint ?? 'v1/image-to-3d', job.model.task, { label: `${id} model` });
  await download(t.model_urls.glb, path.join(dir, 'raw.glb'));
  if (t.thumbnail_url) await download(t.thumbnail_url, path.join(dir, 'thumb.png'));
  job.model.credits = t.consumed_credits;
  saveJob(id, job);
  console.log(`\n${id}: raw.glb`);
}

/** Fill gaps between the UV islands (against light lines when downscaling), all meshes. */
function gutterLayers(doc, W, H, layers) {
  const uv = [], idx = [];
  for (const mesh of doc.getRoot().listMeshes()) for (const p of mesh.listPrimitives()) {
    const u = p.getAttribute('TEXCOORD_0')?.getArray(), ix = p.getIndices()?.getArray();
    if (!u || !ix) continue;
    const base = uv.length / 2;
    uv.push(...u);
    for (const i of ix) idx.push(i + base);
  }
  const id = rasterTriangles(new Float32Array(uv), new Uint32Array(idx), W, H);
  fillGutters(id, W, H, layers, W);
}

/** Magenta → player colour (brightness stays), sRGB 0–255. */
/**
 * Blue areas (slate roofs and bands from the icons) to terracotta: all buildings get the same tile roofs
 * as the house, and blue is a player colour. Brightness is matched to the tiles; magenta (team colour) stays.
 */
export function blueToTerracotta(buf) {
  for (let o = 0; o < buf.length; o += 3) {
    const r = buf[o], g = buf[o + 1], b = buf[o + 2];
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b);
    if (mx !== b || mx - mn < 25) continue;
    // hue 190–260° (blue), softly faded; magenta and violet (red high) stay
    const d = mx - mn;
    const h = r >= g ? 240 + (60 * (r - g)) / d : 240 - (60 * (g - r)) / d;
    const w = Math.min(1, Math.max(0, Math.min(h - 190, 260 - h) / 15)) * Math.min(1, (d / mx - 0.15) / 0.15);
    if (w <= 0) continue;
    // tile tone (190, 85, 58) with the pixel's brightness; blue roofs are darker than tiles, hence × 1.4
    const l = (0.3 * r + 0.59 * g + 0.11 * b) * 1.4;
    const terra = [l * 1.67, l * 0.75, l * 0.51];
    for (let j = 0; j < 3; j++) buf[o + j] = Math.round(Math.min(255, buf[o + j] + (terra[j] - buf[o + j]) * w));
  }
}

export function recolorMarker(buf, color) {
  const tr = (color >> 16) & 255, tg = (color >> 8) & 255, tb = color & 255;
  const tv = Math.max(tr, tg, tb);
  for (let o = 0; o < buf.length; o += 3) {
    const w = markerWeight(buf[o], buf[o + 1], buf[o + 2]);
    if (!w) continue;
    const k = Math.max(buf[o], buf[o + 1], buf[o + 2]) / 255 * (255 / tv) * 0.9;
    const c = [tr * k, tg * k, tb * k];
    for (let j = 0; j < 3; j++) buf[o + j] = Math.round(Math.min(255, buf[o + j] + (c[j] - buf[o + j]) * w));
  }
}

/**
 * Game model: ONE file per model (public/models/buildings/<file>.glb). The pennant stays magenta; the game colours
 * it in the player colour when drawing (as with the characters). Texture 1024² (spec.textureSize), levels of detail without
 * their own texture (the game takes the material of the original).
 */
async function build(id) {
  const spec = readSpec(id), dir = dirOf(id);
  const size = spec.textureSize && spec.textureSize < 1024 ? spec.textureSize : 1024;
  fs.mkdirSync(OUT, { recursive: true });
  const doc = await io.read(path.join(dir, 'raw.glb'));
  const mat = doc.getRoot().listMaterials()[0];
  const baseTex = mat.getBaseColorTexture(), nrmTex = mat.getNormalTexture();
  const dec = async (t) => sharp(Buffer.from(t.getImage())).resize(size, size).removeAlpha().raw().toBuffer();
  const base = await dec(baseTex), nrm = nrmTex ? await dec(nrmTex) : null;
  gutterLayers(doc, size, size, [{ data: base, ch: 3 }, ...(nrm ? [{ data: nrm, ch: 3 }] : [])]);
  if (!spec.keepBlue) blueToTerracotta(base);
  const jpg = (b) => sharp(b, { raw: { width: size, height: size, channels: 3 } }).jpeg({ quality: 88, mozjpeg: true }).toBuffer();
  baseTex.setImage(await jpg(base)).setMimeType('image/jpeg');
  if (nrmTex) nrmTex.setImage(await jpg(nrm)).setMimeType('image/jpeg');
  // Meshy rotates some models: spec.rotate (degrees about the vertical axis) brings the entrance to the front like the other levels
  // models from two views are rotated by 90° at Meshy: compensate automatically (spec.rotate is added)
  const job0 = loadJob(id);
  const rotate = (spec.rotate ?? 0) + (job0.model?.endpoint === 'v1/multi-image-to-3d' ? 90 : 0);
  if (rotate) {
    const a = (rotate * Math.PI) / 360, q = [0, Math.sin(a), 0, Math.cos(a)];
    for (const n of doc.getRoot().getDefaultScene().listChildren()) {
      const [x, y, z, w] = n.getRotation();
      n.setRotation([q[3] * x + q[0] * w + q[1] * z - q[2] * y, q[3] * y - q[0] * z + q[1] * w + q[2] * x, q[3] * z + q[0] * y - q[1] * x + q[2] * w, q[3] * w - q[0] * x - q[1] * y - q[2] * z]);
      const [tx, ty, tz] = n.getTranslation(), c = Math.cos(2 * a), sn = Math.sin(2 * a);
      n.setTranslation([c * tx + sn * tz, ty, -sn * tx + c * tz]);
    }
  }
  mat.setMetallicRoughnessTexture(null).setEmissiveTexture(null).setOcclusionTexture(null).setMetallicFactor(0).setRoughnessFactor(0.85).setName(spec.file);
  await doc.transform(dedup(), prune(), meshopt({ encoder: MeshoptEncoder, level: 'medium' }));
  const file = path.join(OUT, `${spec.file}.glb`);
  await io.write(file, doc);
  // remove old versions per player colour
  for (const f of fs.readdirSync(OUT)) if (new RegExp(`^${spec.file}_(blue|red|green|yellow)(\\.lod\\d)?\\.glb$`).test(f)) fs.unlinkSync(path.join(OUT, f));
  // levels of detail (fewer triangles, without texture)
  execFileSync(process.execPath, [path.join(ROOT, 'scripts/build-lods.mjs'), file], { stdio: 'ignore' });
  console.log(`${path.basename(file)}: ${(fs.statSync(file).size / 1024).toFixed(0)} KB`);
}

const argv = process.argv.slice(2);
const flag = (n) => { const i = argv.indexOf(n); if (i < 0) return undefined; const v = argv[i + 1]; argv.splice(i, 2); return v; };
const opts = { model: flag('--model'), out: flag('--out'), effort: flag('--effort') };
const [cmd, id, arg] = argv;
if (import.meta.url === `file://${process.argv[1]}`) {
  requireAssetsSrc('buildings');
  reexecWithProxy();
  try {
    if (cmd === 'concept') await concept(id, opts);
    else if (cmd === 'set') await conceptSet(id.split(','), opts);
    else if (cmd === 'cut') { // cut out the chosen level set again: cut a,b,c set-v2
      const ids = id.split(','), parts = await splitColumns(path.join(DIR, ids[0], arg), ids.length);
      ids.forEach((x, i) => { fs.writeFileSync(path.join(dirOf(x), 'concept.png'), parts[i]); const job = loadJob(x); job.cut = arg; saveJob(x, job); });
    }
    else if (cmd === 'back') for (const x of id.split(',')) await backView(x, opts);
    else if (cmd === 'winter') for (const x of id.split(',')) await winterView(x, opts);
    else if (cmd === 'pick') pick(id, arg);
    else if (cmd === 'model') await model(id);
    else if (cmd === 'build') await build(id);
    else if (cmd === 'all') { await concept(id); await model(id); await build(id); }
    else { console.error('Usage: building.mjs concept|model|build|all <id>'); process.exit(1); }
  } catch (err) { console.error('\n' + err.message); process.exit(1); }
}
